export const droitPage = (chemin) => DROITS_PAGES[String(chemin || '').split('?')[0]] ?? null;

export const aDroitPour = (user, code) => !code || Boolean(user?.admin) || (user?.privileges ?? []).includes(code);

export function useDroits() {
  const user = useSelector(selectUtilisateur);
  return useCallback((code) => aDroitPour(user, code), [user]);
}
